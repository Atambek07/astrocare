def _document_provenance(
    provenance_id: str,
    *,
    document_id: str,
    title: str,
    source_url: str,
    source_publication: str | None,
    notes: str,
) -> ProvenanceRecord:
    """Provenance для официального документа NASA или демо-протокола."""
    return ProvenanceRecord(
        provenance_id=provenance_id,
        source_type=SourceType.NASA_REAL,
        nasa_study_id=None,
        nasa_dataset_id=document_id,
        source_file=None,
        source_url=source_url,
        publication_reference=source_publication,
        subject_id=None,
        collection_timepoint=None,
        measurement_timestamp=None,
        measurement_unit=None,
        original_value=None,
        normalized_value=None,
        processing_method="source_document_registration",
        quality_status=QualityStatus.VALIDATED,
        metric_key="reference_document",
        fallback_status=FallbackStatus.NONE,
        derived_from=[],
        source_verified_utc=VERIFIED_AT,
        notes=notes,
        source_publication=source_publication,
        measurement_name=title,
        original_unit=None,
        normalized_unit=None,
        processing_version="knowledge-registry-1.0.0",
        generated_at_utc=utc_now_iso(),
        source_file_sha256=None,
        license_or_access_terms="NASA public website or public technical standard. See source URL.",
        download_timestamp=None,
        processing_timestamp=utc_now_iso(),
        pipeline_version="astralis-data-1.0.0",
        generator_name=None,
        generator_version=None,
        random_seed=None,
        scenario_id=None,
        scenario_configuration=None,
        generation_timestamp=None,
    )


